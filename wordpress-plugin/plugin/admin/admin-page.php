        } else {
            echo '<p style="color: #b00;"><strong>' . esc_html__('No data imported yet.', 'crescent-visibility') . '</strong> '
                . esc_html__('Please upload a data file above.', 'crescent-visibility') . '</p>';
        }

        // Outcome of the most recent import attempt (persisted), visible on every load.
        $last = get_option('cvi_last_import');
        if (is_array($last)) {
            echo '<h3>' . esc_html__('Last Import Attempt', 'crescent-visibility') . '</h3>';
            echo '<table class="widefat striped" style="max-width:560px;"><tbody>';
            $row = function ($k, $v) { echo '<tr><td><strong>' . esc_html($k) . '</strong></td><td>' . esc_html($v) . '</td></tr>'; };
            /* translators for the diagnostic labels below are self-evident field names. */
            if (!empty($last['time']))          { $row(__('When', 'crescent-visibility'), $last['time']); }
            if (isset($last['file_size']))      { $row(__('Uploaded file size', 'crescent-visibility'), sprintf(__('%s bytes', 'crescent-visibility'), number_format((int) $last['file_size']))); }
            if (!empty($last['error']))         { $row(__('Result', 'crescent-visibility'), sprintf(__('FAILED — %s', 'crescent-visibility'), $last['error'])); }
            if (isset($last['found']))          { $row(__('Observations in file', 'crescent-visibility'), intval($last['found'])); }
            if (isset($last['imported']))       { $row(__('Stored this import', 'crescent-visibility'), intval($last['imported'])); }
            if (!empty($last['skipped']))       { $row(__('Skipped (missing city/new_moon)', 'crescent-visibility'), intval($last['skipped'])); }
            if (!empty($last['failed']))        { $row(__('DB errors', 'crescent-visibility'), intval($last['failed'])); }
            if (isset($last['stored_total']))   { $row(__('Total rows now in table', 'crescent-visibility'), intval($last['stored_total'])); }
            if (isset($last['id_column']))      { $row(__('id column type', 'crescent-visibility'), $last['id_column'] !== '' ? $last['id_column'] : __('(no AUTO_INCREMENT)', 'crescent-visibility')); }
            if (isset($last['indexes']))        { $row(__('Indexes', 'crescent-visibility'), $last['indexes']); }
            if (isset($last['distinct_pairs'])) { $row(__('Distinct city+date stored', 'crescent-visibility'), intval($last['distinct_pairs'])); }
            if (!empty($last['sample_rows']))   { $row(__('First stored rows', 'crescent-visibility'), $last['sample_rows']); }
            if (!empty($last['ddl_error']))     { $row(__('Table rebuild error', 'crescent-visibility'), $last['ddl_error']); }
            if (!empty($last['first_error']))   { $row(__('First DB error', 'crescent-visibility'), $last['first_error']); }
            if (!empty($last['first_skip']))    { $row(__('First skipped row', 'crescent-visibility'), $last['first_skip']); }
