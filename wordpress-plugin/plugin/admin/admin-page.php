        $count = (int) $wpdb->get_var("SELECT COUNT(*) FROM $table");

        if ($count > 0) {
            echo '<p style="color: green;"><strong>' . esc_html__('✓ Data loaded:', 'crescent-visibility') . '</strong> '
                /* translators: %s: number of observation records */
                . esc_html(sprintf(_n('%s observation record in the database.', '%s observation records in the database.', $count, 'crescent-visibility'), number_format($count)))
